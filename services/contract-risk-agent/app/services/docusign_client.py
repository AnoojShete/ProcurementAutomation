"""DocuSign eSignature REST API (v2.1), sandbox by default.

Authentication is the JWT grant ("service integration"): we sign a short
JWT with the app's RSA private key, swap it for an access token at
DocuSign's OAuth server, and act as the configured DocuSign user. That
user has to grant consent once — the control panel shows the consent link
when DocuSign answers `consent_required`.

Sending creates an envelope with status "sent": DocuSign itself emails the
signer once, with a link to sign. Completion is picked up either by the
status poller (run_status_poller, no public URL needed) or by DocuSign
Connect calling POST /webhooks/docusign — both end in mark_contract_signed,
which is idempotent, so a contract is marked signed once.

Provider reference stored on the contract: docusign-env-<envelope id>.
"""
import asyncio
import base64
import hashlib
import hmac
import logging
import time
from datetime import datetime, timezone
from typing import Optional
from urllib.parse import urlencode

import httpx
import jwt

from app.config import settings

logger = logging.getLogger(__name__)

DOCUSIGN_REF_PREFIX = "docusign-env-"
_TIMEOUT = httpx.Timeout(30.0)
_token: dict = {"value": None, "expires_at": 0.0}


class DocuSignError(Exception):
    pass


class DocuSignConsentRequired(DocuSignError):
    pass


def docusign_enabled() -> bool:
    return bool(
        settings.docusign_integration_key and settings.docusign_user_id and settings.docusign_account_id
        and (settings.docusign_private_key or settings.docusign_private_key_file)
    )


def envelope_id(provider_ref: Optional[str]) -> Optional[str]:
    if provider_ref and provider_ref.startswith(DOCUSIGN_REF_PREFIX):
        return provider_ref[len(DOCUSIGN_REF_PREFIX):]
    return None


def consent_url() -> Optional[str]:
    if not settings.docusign_integration_key:
        return None
    query = urlencode({
        "response_type": "code",
        "scope": "signature impersonation",
        "client_id": settings.docusign_integration_key,
        "redirect_uri": settings.docusign_redirect_uri,
    })
    return f"https://{settings.docusign_auth_server}/oauth/auth?{query}"


def _private_key() -> str:
    if settings.docusign_private_key:
        return settings.docusign_private_key.replace("\\n", "\n")
    with open(settings.docusign_private_key_file) as f:
        return f.read()


def build_jwt_assertion(now: Optional[int] = None) -> str:
    now = int(now if now is not None else time.time())
    claims = {
        "iss": settings.docusign_integration_key,
        "sub": settings.docusign_user_id,
        "aud": settings.docusign_auth_server,
        "iat": now,
        "exp": now + 3600,
        "scope": "signature impersonation",
    }
    return jwt.encode(claims, _private_key(), algorithm="RS256")


async def access_token() -> str:
    """Cached until a minute before it expires."""
    if _token["value"] and time.time() < _token["expires_at"] - 60:
        return _token["value"]
    async with httpx.AsyncClient(timeout=_TIMEOUT) as client:
        res = await client.post(
            f"https://{settings.docusign_auth_server}/oauth/token",
            data={"grant_type": "urn:ietf:params:oauth:grant-type:jwt-bearer", "assertion": build_jwt_assertion()},
        )
    if res.status_code >= 400:
        error = res.json().get("error", "") if res.headers.get("content-type", "").startswith("application/json") else ""
        if error == "consent_required":
            raise DocuSignConsentRequired("the DocuSign user hasn't granted consent to this app yet")
        raise DocuSignError(f"DocuSign login failed ({res.status_code}): {error or res.text[:200]}")
    body = res.json()
    _token["value"] = body["access_token"]
    _token["expires_at"] = time.time() + int(body.get("expires_in", 3600))
    return _token["value"]


async def _api(method: str, path: str, **kwargs) -> httpx.Response:
    token = await access_token()
    url = f"{settings.docusign_base_url.rstrip('/')}/v2.1/accounts/{settings.docusign_account_id}{path}"
    async with httpx.AsyncClient(timeout=_TIMEOUT) as client:
        res = await client.request(method, url, headers={"Authorization": f"Bearer {token}"}, **kwargs)
    if res.status_code >= 400:
        raise DocuSignError(f"DocuSign {method} {path} failed ({res.status_code}): {res.text[:300]}")
    return res


def envelope_definition(contract_id: str, signer_email: str, signer_name: str, pdf: bytes, title: str) -> dict:
    return {
        "emailSubject": f"Please sign: {title}"[:100],
        "emailBlurb": "This contract was generated by the IT Procurement Intelligence Platform.",
        "documents": [{
            "documentBase64": base64.b64encode(pdf).decode(),
            "name": title[:100],
            "fileExtension": "pdf",
            "documentId": "1",
        }],
        "recipients": {"signers": [{
            "email": signer_email,
            "name": signer_name,
            "recipientId": "1",
            "routingOrder": "1",
            # Over the "For the Company" signature line contract_pdf draws.
            "tabs": {"signHereTabs": [{
                "anchorString": "For the Company",
                "anchorUnits": "pixels",
                "anchorXOffset": "0",
                "anchorYOffset": "38",
                "anchorIgnoreIfNotPresent": "false",
            }]},
        }]},
        "customFields": {"textCustomFields": [{"name": "contract_id", "value": contract_id, "show": "false"}]},
        "status": "sent",
    }


async def send_envelope(contract_id: str, signer_email: str, signer_name: str, pdf: bytes, title: str) -> str:
    res = await _api("POST", "/envelopes", json=envelope_definition(contract_id, signer_email, signer_name, pdf, title))
    env_id = res.json()["envelopeId"]
    logger.info(f"Contract {contract_id} sent to DocuSign as envelope {env_id} (signer {signer_email})")
    return f"{DOCUSIGN_REF_PREFIX}{env_id}"


async def get_envelope(env_id: str) -> dict:
    return (await _api("GET", f"/envelopes/{env_id}", params={"include": "recipients"})).json()


async def download_combined(env_id: str) -> bytes:
    """The completed document plus DocuSign's certificate of completion."""
    return (await _api("GET", f"/envelopes/{env_id}/documents/combined")).content


def completion(envelope: dict) -> Optional[tuple[str, datetime]]:
    """(signed_by, signed_at) for a completed envelope, else None."""
    if envelope.get("status") != "completed":
        return None
    signers = (envelope.get("recipients") or {}).get("signers") or []
    signed_by = ", ".join(s.get("email", "") for s in signers if s.get("email")) or "DocuSign signer"
    stamp = envelope.get("completedDateTime") or (signers[0].get("signedDateTime") if signers else None)
    signed_at = datetime.fromisoformat(stamp.replace("Z", "+00:00")) if stamp else datetime.now(timezone.utc)
    return signed_by, signed_at


def verify_connect_signature(raw_body: bytes, signatures: list[str]) -> bool:
    """DocuSign Connect HMAC: base64(HMAC-SHA256(key, raw body)) in
    X-DocuSign-Signature-1 (-2… after a key rotation)."""
    key = settings.docusign_connect_hmac_key
    if not key:
        return False
    expected = base64.b64encode(hmac.new(key.encode(), raw_body, hashlib.sha256).digest()).decode()
    return any(sig and hmac.compare_digest(expected, sig) for sig in signatures)


async def connection_status() -> dict:
    """For the control panel: configured? can we log in?"""
    status = {
        "configured": docusign_enabled(),
        "environment": "sandbox" if "demo." in settings.docusign_base_url else "production",
        "base_url": settings.docusign_base_url,
        "account_id": settings.docusign_account_id,
        "connected": False,
        "error": None,
        "consent_url": None,
        "connect_webhook": bool(settings.docusign_connect_hmac_key),
        "poll_seconds": settings.docusign_poll_seconds,
    }
    if not status["configured"]:
        return status
    try:
        await access_token()
        status["connected"] = True
    except DocuSignConsentRequired as e:
        status["error"], status["consent_url"] = str(e), consent_url()
    except Exception as e:
        status["error"] = str(e)
    return status


async def poll_once(session_factory, kafka_producer) -> int:
    """Marks contracts whose DocuSign envelope completed as signed. Returns
    how many were marked."""
    from sqlalchemy import select
    from app.models import Contract
    from app.services.webhook_service import WebhookReplayError, mark_contract_signed

    async with session_factory() as db:
        pending = (await db.execute(
            select(Contract.id, Contract.esign_provider_ref).where(
                Contract.status == "pending_signature",
                Contract.esign_provider_ref.like(f"{DOCUSIGN_REF_PREFIX}%"),
            )
        )).all()
    marked = 0
    for contract_id, ref in pending:
        env_id = envelope_id(ref)
        try:
            done = completion(await get_envelope(env_id))
        except Exception as e:
            logger.warning(f"DocuSign status check for envelope {env_id} failed: {e}")
            continue
        if done is None:
            continue
        signed_by, signed_at = done
        async with session_factory() as db:
            try:
                await mark_contract_signed(
                    db, kafka_producer, contract_id=str(contract_id), signed_by=signed_by, signed_at=signed_at,
                    provider_event_id=f"docusign-{env_id}-completed", source="signed_via_docusign",
                )
                marked += 1
                logger.info(f"Contract {contract_id} signed in DocuSign by {signed_by}")
            except WebhookReplayError:
                pass  # Connect got there first
    return marked


async def run_status_poller(session_factory, kafka_producer) -> None:
    if not docusign_enabled():
        return
    while True:
        try:
            await poll_once(session_factory, kafka_producer)
        except asyncio.CancelledError:
            raise
        except Exception as e:
            logger.warning(f"DocuSign status poll failed: {e}")
        await asyncio.sleep(settings.docusign_poll_seconds)
